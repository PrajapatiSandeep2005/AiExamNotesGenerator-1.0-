import { useState } from 'react'
import ReactMarkdown from 'react-markdown';
import MermaidSetup from './MermaidSetup';
import RechartSetup from './RechartSetup';
import { downloadPdf } from '../services/api';
import { formatNoteValue } from '../utils/formatNoteValue';
import { motion } from 'framer-motion';

const markDownComponent = {
  h1: ({ children }) => (<h1 className='text-2xl font-bold mb-4 mt-6 border-b border-[#d49a54]/20 pb-2 text-[#ffc06b]'>
    {children}
  </h1>
  ),
  h2: ({ children }) => (<h2 className='text-xl font-semibold mb-3 mt-5 text-[#f5a13b]'>
    {children}
  </h2>
  ),
  h3: ({ children }) => (<h3 className='text-lg font-semibold mb-2 mt-4 text-gray-100'>
    {children}
  </h3>
  ),
  p: ({ children }) => (
    <p className='text-gray-300 mb-3 loading-relaxed'>
      {children}
    </p>
  ),
  ul: ({ children }) => (
    <ul className='list-disc ml-6 space-y-1 text-gray-300 mb-3'>
      {children}
    </ul>
  ),
  li: ({ children }) => (
    <li className='marker:text-[#f5a13b]'>{children}</li>
  ),
}

function FinalResult({ results }) {
  const [quickRevision, setQuickRevision] = useState(false);

  // Extract the nested 'content' object where all the AI data actually lives
  const data = results?.content;

  // Update the safety check to validate 'data' instead of 'results' directly
  if (!data ||
    !data.subTopics ||
    !data.questions ||
    !data.questions.short ||
    !data.questions.long
  ) {
    return null;
  }

  return (
    <motion.div
      initial={{ opacity: 0, y: 10 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.35 }}
      className='p-3 space-y-8 bg-transparent text-[#eee9e1]'
    >
      <motion.div
        initial={{ opacity: 0, y: -8 }}
        animate={{ opacity: 1, y: 0 }}
        transition={{ duration: 0.35 }}
        className='flex flex-col md:flex-row md:items-center md:justify-between gap-4'
      >

        <h2 className='text-2xl font-bold text-[#f5a13b]'>
          📗 Generated Notes
        </h2>
        {results.providerUsed && (
          <span className="w-fit rounded-full border border-[#f5a13b]/30 bg-[#f5a13b]/10 px-3 py-1 text-xs font-medium text-[#ffc06b]">
            Generated by {results.providerUsed}
          </span>
        )}

        <div className='flex  gap-4'>
          {results.revisionMode && (
            <button
              onClick={() => setQuickRevision(!quickRevision)}
              className={`px-4 py-2 rounded-lg text-sm font-medium cursor-pointer transition ${quickRevision
                  ? "bg-[#f5a13b] text-[#17110a]"
                  : "bg-[#2a2015] text-[#ffc06b] hover:bg-[#3a2b1b]"
                }`}
            >
              {quickRevision
                ? "Exit Revision Mode"
                : "Quick Revision Mode (5 mins)"}
            </button>
          )}

          <button onClick={() => downloadPdf(results)}
            className='px-4 py-2 rounded-lg text-sm cursor-pointer font-medium bg-[#f5a13b] text-[#17110a] hover:bg-[#ffb858]'>
            ⬇️ Download PDF
          </button>
        </div>
      </motion.div>


      {!quickRevision && <section>

        <SectionHeader icon="⭐" title="Sub Topics" color="indigo" />
        {
          Object.entries(data.subTopics).map(([star, topics]) => (
            <div key={star}>
              <p className='font-medium text-[#ffc06b] mb-1'>
                {star} Priority
              </p>
              <ul className='list-disc ml-6 text-gray-300'>
                {topics.map((topic, i) => (
                  <li key={i}>{formatNoteValue(topic)}</li>
                ))}
              </ul>
            </div>
          ))
        }
      </section>}


      {!quickRevision && <section>
        <SectionHeader icon="📝" title="Detailed Notes" color="purple" />
        <div className='bg-[#0b0c0d] border border-[#d49a54]/20 rounded-xl p-5'>
          <ReactMarkdown components={markDownComponent}>
            {data.notes}
          </ReactMarkdown>
        </div>
      </section>}


      {results.revisionMode && quickRevision && (
    <section className="rounded-xl bg-[#211b13] p-6 border border-[#d49a54]/25">
        <h3 className="font-bold text-[#ffc06b] mb-3 text-lg">
            ⚡ Quick Revision Points
        </h3>

        <ul className="list-disc ml-6 text-gray-300 space-y-2">
            {(data.revisionPoints || []).map((point, i) => (
                <li key={i}>{formatNoteValue(point)}</li>
            ))}
        </ul>
    </section>
)}

      {data.diagram &&
        <section>
          <SectionHeader icon="📊" title="Diagram" color="cyan" />
          <MermaidSetup diagram={data.diagram?.data} />
          <p className='text-sm text-gray-400 mt-2 italic'>
            ℹ️ If you need this diagram for future reference or revision , consider taking a screenshot and save it.
          </p>
        </section>
      }

      {data.charts?.length > 0 &&
        <section>
          <SectionHeader icon="📈" title="Charts" color="indigo" />
          <RechartSetup charts={data.charts} />
          <p className='text-sm text-gray-400 mt-2 italic'>
            ℹ️ If you need this charts for future reference or revision , consider taking a screenshot and save it.
          </p>
        </section>}

      {data.charts && data.charts.length === 0 && (
        <p className='text-sm text-gray-400 mt-2 italic'>
          📉 Charts are not relevant for this topic
        </p>
      )}

      <section>
        <SectionHeader icon="❓" title="Important Questions" color="rose" />

        <p className='font-medium text-[#ffc06b]'> Short Questions</p>
        <ul className='list-disc ml-6 text-gray-300'>
          {data.questions.short.map((question, i) => (
            <li key={i}>{formatNoteValue(question)}</li>
          ))}
        </ul>

        <p className='font-medium mt-4 text-[#ffc06b]'> Long Questions</p>
        <ul className='list-disc ml-6 text-gray-300'>
          {data.questions.long.map((question, i) => (
            <li key={i}>{formatNoteValue(question)}</li>
          ))}
        </ul>

        {data.questions.diagram && (
          <>
            <p className='font-medium mt-4 text-[#ffc06b]'> Diagram Questions</p>
            <ul className='list-disc ml-6 text-gray-300'>
              <li>{formatNoteValue(data.questions.diagram)}</li>
            </ul>
          </>
        )}
      </section>

    </motion.div>
  );
}

function SectionHeader({ title, icon, color }) {
  const colors = {
    indigo: "from-[#2a2015] to-[#211b13] text-[#ffc06b]",
    purple: "from-[#2a2015] to-[#211b13] text-[#ffc06b]",
    blue: "from-[#2a2015] to-[#211b13] text-[#ffc06b]",
    green: "from-[#2a2015] to-[#211b13] text-[#ffc06b]",
    cyan: "from-[#2a2015] to-[#211b13] text-[#ffc06b]",
    rose: "from-[#2a2015] to-[#211b13] text-[#ffc06b]",
  };
  return (
    <motion.div
      initial={{ opacity: 0, x: -8 }}
      animate={{ opacity: 1, x: 0 }}
      transition={{ duration: 0.3 }}
      className={`mb-4 px-3 py-2 rounded-lg bg-gradient-to-r ${colors[color]} font-semibold flex items-center gap-2`}
    >
      <span>{icon}</span>
      <span>{title}</span>
    </motion.div>
  )
}

export default FinalResult;